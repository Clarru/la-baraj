import { afterEach, describe, expect, it, vi } from "vitest";
import { renderToStaticMarkup } from "react-dom/server";
import { NameOnboarding } from "./NameOnboarding";
import { readPlayerName, savePlayerName, validPlayerName } from "./player-name";
import { Minimap } from "./Minimap";
import { createNavigationFeed } from "./navigation-feed";
afterEach(() => vi.unstubAllGlobals());
describe("first entry and chosen player names", () => {
  it("does not turn old autogenerated labels into a confirmed name", () => {
    vi.stubGlobal("localStorage", {
      getItem: (key: string) =>
        key === "lake-cincis-nickname" ? "Wild Heron 86" : null,
    });
    expect(readPlayerName()).toBeNull();
    const html = renderToStaticMarkup(<NameOnboarding onEnter={() => {}} />);
    expect(html).toContain("What should we call you?");
    expect(html).toContain("Enter La Baraj");
    expect(html).toContain('autoComplete="nickname"');
    expect(html).toContain('value=""');
    expect(html).not.toContain("Wild Heron");
  });
  it("validates, explicitly saves, and restores names, including Romanian characters", () => {
    const values = new Map<string, string>();
    vi.stubGlobal("localStorage", {
      getItem: (key: string) => values.get(key) ?? null,
      setItem: (key: string, value: string) => values.set(key, value),
    });
    expect(savePlayerName("  Ștefan  ")).toBe("Ștefan");
    expect(readPlayerName()).toBe("Ștefan");
    for (const name of ["", "   ", "x".repeat(25), "<name>", "bad\nname"])
      expect(validPlayerName(name)).toBe(false);
    expect(() => savePlayerName("<name>")).toThrow();
  });
  it("allows current-session entry even when browser storage is blocked", () => {
    vi.stubGlobal("localStorage", {
      getItem() {
        throw Error("blocked");
      },
      setItem() {
        throw Error("blocked");
      },
    });
    expect(readPlayerName()).toBeNull();
    expect(savePlayerName("Clau")).toBe("Clau");
  });
  it("renders only allocated cabin markers and no home marker before assignment", () => {
    const navigation = createNavigationFeed({ x: 0, z: 0, heading: 0 });
    const empty = renderToStaticMarkup(
      <Minimap navigation={navigation} homeIndex={null} cabins={[]} />,
    );
    expect(empty).not.toContain('data-testid="home-map-marker"');
    const village = renderToStaticMarkup(
      <Minimap
        navigation={navigation}
        homeIndex={1}
        cabins={[
          { index: 0, ownerName: "Clau" },
          { index: 1, ownerName: null },
        ]}
      />,
    );
    expect((village.match(/<title>Cabin /g) ?? []).length).toBe(2);
    expect(village).not.toContain("Cabin 3 ·");
  });
});
